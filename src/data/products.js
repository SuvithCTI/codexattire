import storage from '../utils/storage';

export const getLiveProducts = () => {
  const saved = storage.get('products', null);
  if (!saved || !Array.isArray(saved) || saved.length === 0) {
    const initialized = PRODUCTS.map((p, idx) => {
      const sampleStock = idx === 3 ? 3 : idx === 7 ? 0 : 25;
      return {
        ...p,
        stock: p.stock !== undefined ? p.stock : sampleStock,
        inStock: p.stock !== undefined ? p.stock > 0 : sampleStock > 0,
      };
    });
    storage.set('products', initialized);
    return initialized;
  }
  return saved.map((p) => {
    const stockQty = p.stock !== undefined ? p.stock : (p.inStock === false ? 0 : 20);
    return {
      ...p,
      stock: stockQty,
      inStock: stockQty > 0,
    };
  });
};

export const getFeaturedProducts = () => getLiveProducts().filter(p => p.isFeatured);
export const getNewArrivals = () => getLiveProducts().filter(p => p.isNewArrival);
export const getProductsByCategory = (cat) => getLiveProducts().filter(p => p.category.toLowerCase() === cat.toLowerCase());
export const getProductById = (id) => getLiveProducts().find(p => p.id === id);
